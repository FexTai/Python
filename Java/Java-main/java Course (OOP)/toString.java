public class toString {
    public static void main(String[] args) {

        // toString() = special method that all objects inherit,
        //              that returns a string, which textually represents an object
        //              can be used both simplicity and explicity

        Car_1 car = new Car_1();

        System.out.println(car); //due toString method in Car class outputs are the same
        System.out.println(car.toString());


    }
}
